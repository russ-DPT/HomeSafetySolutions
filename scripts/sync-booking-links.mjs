// 1. Builds one static Before You Book page per service from
//    public/before-you-book.html (the generic, no-service version).
// 2. Writes the PracticeQ URL from lib/booking-links.mjs into the href of
//    every element carrying data-link="KEY" across public/*.html.
// Runs on every build (see package.json), so a URL changed in the config
// reaches the whole site without editing any page.
import { readFileSync, writeFileSync, readdirSync, unlinkSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"
import { LINKS, BEFORE_YOU_BOOK } from "../lib/booking-links.mjs"

const PUBLIC = join(dirname(fileURLToPath(import.meta.url)), "..", "public")
const TEMPLATE = "before-you-book.html"
const VARIANT_PREFIX = "before-you-book-"

function replaceRegion(html, name, content) {
  const re = new RegExp(`(<!-- bfb:${name} -->)[\\s\\S]*?(<!-- /bfb:${name} -->)`)
  if (!re.test(html)) throw new Error(`Missing region bfb:${name} in ${TEMPLATE}`)
  return html.replace(re, `$1\n${content}\n$2`)
}

function buildVariants() {
  for (const f of readdirSync(PUBLIC)) if (f.startsWith(VARIANT_PREFIX) && f.endsWith(".html")) unlinkSync(join(PUBLIC, f))
  const template = readFileSync(join(PUBLIC, TEMPLATE), "utf8")
  for (const [key, svc] of Object.entries(BEFORE_YOU_BOOK)) {
    let html = template.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/sync-booking-links.mjs from before-you-book.html. Do not edit. -->")
    html = replaceRegion(html, "intro",
      `<p class="lede">You chose the ${svc.name}. That may be exactly what you need, and you are welcome to book it below. Before you do, most people start with a short phone call. Here is why.</p>`)
    html = replaceRegion(html, "urgent", svc.urgent
      ? `<div class="bfb-urgent"><p><strong>Is discharge in the next few days?</strong> Time matters. You can book the visit directly below, or call <a href="tel:+18138673372">(813) 867-3372</a> and we will fit your consultation in quickly.</p></div>`
      : "")
    const buttons = svc.options.map(([label, link]) => `<a class="btn btn-secondary" href="" data-link="${link}">${label}</a>`).join("\n        ")
    html = replaceRegion(html, "cardb",
      `<article class="bfb-card bfb-card-b" aria-labelledby="bfb-b-h">
      <h2 id="bfb-b-h">I&apos;m ready to book the ${svc.name}</h2>
      <p>Choose how you would like the visit:</p>
      <div class="bfb-buttons">
        ${buttons}
      </div>
      <p class="bfb-small">We will call to confirm your details and take payment by phone after you book.</p>
    </article>`)
    html = replaceRegion(html, "allservices", "")
    writeFileSync(join(PUBLIC, `${VARIANT_PREFIX}${key}.html`), html)
  }
}

function syncHrefs() {
  const tagRe = /<a\b[^>]*\bdata-link="([A-Z_]+)"[^>]*>/g
  let total = 0
  for (const f of readdirSync(PUBLIC).filter((f) => f.endsWith(".html"))) {
    const path = join(PUBLIC, f)
    const src = readFileSync(path, "utf8")
    const out = src.replace(tagRe, (tag, key) => {
      const url = LINKS[key]
      if (!url) throw new Error(`Unknown data-link "${key}" in ${f}`)
      total++
      return /\bhref="[^"]*"/.test(tag) ? tag.replace(/\bhref="[^"]*"/, `href="${url}"`) : tag.replace("<a", `<a href="${url}"`)
    })
    if (out !== src) writeFileSync(path, out)
  }
  return total
}

buildVariants()
console.log(`Before You Book: ${Object.keys(BEFORE_YOU_BOOK).length} service pages built. PracticeQ links synced: ${syncHrefs()}.`)
